-- Q1) เวลารวมต่อวัน (ไม่นับรายการที่ยกเลิก) + เวลาที่เหลือจาก 480 + สถานะ
SELECT  "WorkDate"                                                        AS วันที่,
        COALESCE(SUM("Minutes") FILTER (WHERE NOT "IsCancelled"), 0)      AS เวลารวม_นาที,
        480 - COALESCE(SUM("Minutes") FILTER (WHERE NOT "IsCancelled"), 0) AS เหลือได้อีก_นาที,
        COUNT(*) FILTER (WHERE NOT "IsCancelled")                         AS จำนวนรายการ,
        COUNT(*) FILTER (WHERE "IsCancelled")                             AS ยกเลิก,
        CASE WHEN COALESCE(SUM("Minutes") FILTER (WHERE NOT "IsCancelled"), 0) > 480 THEN 'เกิน 480'
             WHEN COALESCE(SUM("Minutes") FILTER (WHERE NOT "IsCancelled"), 0) = 480 THEN 'เต็มพอดี'
             ELSE 'ไม่เกิน' END                                             AS สถานะ
FROM    "TimeEntries"
GROUP BY "WorkDate"
ORDER BY "WorkDate";

-- Q2) เวลารวมแยกตามโครงการในช่วงวันที่ (ไม่นับรายการที่ยกเลิก)
SELECT  p."Id"                         AS รหัสโครงการ,
        p."Name"                       AS โครงการ,
        SUM(t."Minutes")               AS เวลารวม_นาที,
        ROUND(SUM(t."Minutes") / 60.0, 2) AS เวลารวม_ชั่วโมง,
        COUNT(*)                       AS จำนวนรายการ
FROM    "TimeEntries" t
JOIN    "Projects" p ON p."Id" = t."ProjectId"
WHERE   NOT t."IsCancelled"
  AND   t."WorkDate" BETWEEN DATE '2026-11-02' AND DATE '2026-11-06'
GROUP BY p."Id", p."Name"
ORDER BY เวลารวม_นาที DESC;

-- Q3) ตรวจกติกา 480 นาที "ตอนแก้ไข" (เหมือน TimeEntryService.UpdateAsync)
--     ตัวอย่าง: แก้รายการ Id 6 (ประชุม 90 นาที วันที่ 3 พ.ย. ซึ่งเต็ม 480 แล้ว) เป็น 100 นาที
--     รวม = (รายการอื่นในวันใหม่ที่ไม่ถูกยกเลิก ไม่นับรายการที่กำลังแก้) + Minutes ใหม่
--     → 240 + 150 + 100 = 490 → ไม่ผ่าน (เหลือได้อีก 90 นาที)
WITH edit AS (
    SELECT 6 AS entry_id, DATE '2026-11-03' AS new_work_date, 100 AS new_minutes
)
SELECT  e.new_work_date                                          AS วันที่ใหม่,
        COALESCE(SUM(t."Minutes"), 0)                            AS รายการอื่น_นาที,
        e.new_minutes                                            AS ค่าใหม่_นาที,
        COALESCE(SUM(t."Minutes"), 0) + e.new_minutes            AS รวมหลังแก้_นาที,
        GREATEST(0, 480 - COALESCE(SUM(t."Minutes"), 0))         AS เหลือได้อีก_นาที,
        CASE WHEN e.new_minutes BETWEEN 1 AND 480
              AND COALESCE(SUM(t."Minutes"), 0) + e.new_minutes <= 480
             THEN 'ผ่าน' ELSE 'ไม่ผ่าน' END                       AS ผลตรวจ
FROM    edit e
LEFT JOIN "TimeEntries" t
       ON t."WorkDate" = e.new_work_date
      AND NOT t."IsCancelled"
      AND t."Id" <> e.entry_id
GROUP BY e.new_work_date, e.new_minutes;

-- Q4) ตรวจก่อน "กู้คืน" รายการที่ยกเลิก (Id 9 วันที่ 4 พ.ย.): 390 + 120 = 510 → ไม่ผ่าน
SELECT  c."Id",
        (SELECT COALESCE(SUM("Minutes"), 0) FROM "TimeEntries"
          WHERE "WorkDate" = c."WorkDate" AND NOT "IsCancelled" AND "Id" <> c."Id") + c."Minutes" AS รวมหลังกู้คืน_นาที,
        CASE WHEN (SELECT COALESCE(SUM("Minutes"), 0) FROM "TimeEntries"
                    WHERE "WorkDate" = c."WorkDate" AND NOT "IsCancelled" AND "Id" <> c."Id") + c."Minutes" <= 480
             THEN 'กู้คืนได้' ELSE 'กู้คืนไม่ได้ (เกิน 480)' END AS ผลตรวจ
FROM    "TimeEntries" c
WHERE   c."Id" = 9;

-- Q5) รายการของวันหนึ่ง พร้อมชื่อโครงการ (รวมรายการที่ยกเลิก)
SELECT  t."Id", t."WorkDate", p."Name" AS โครงการ, t."Description", t."Minutes", t."Note",
        CASE WHEN t."IsCancelled" THEN 'ยกเลิก' ELSE 'ปกติ' END AS สถานะ
FROM    "TimeEntries" t
JOIN    "Projects" p ON p."Id" = t."ProjectId"
WHERE   t."WorkDate" = DATE '2026-11-04'
ORDER BY t."CreatedAt";

